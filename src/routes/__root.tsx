function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  const [recovery, setRecovery] = useState(false);
  useEffect(() => {
    const { data } = supabase.auth.onAuthStateChange((event) => {
      if (event === "PASSWORD_RECOVERY") { setRecovery(true); return; }
      if (event === "SIGNED_OUT") setRecovery(false);
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  useEffect(() => {
    initAnalytics();
    trackPageView(router.state.location.pathname);
    return router.subscribe("onResolved", ({ toLocation, pathChanged }) => {
      if (pathChanged) trackPageView(toLocation.pathname);
    });
  }, [router]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <RecoveryContext value={recovery}><Outlet /></RecoveryContext>
    </QueryClientProvider>
  );
}
